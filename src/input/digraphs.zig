/// The character `a` then `b` stand for; the pair the other way round
/// counts too (as in Vim), when it isn't one itself.
pub fn find(a: u21, b: u21) ?u21 {
    if (a > 0x7f or b > 0x7f) return null;
    for (table) |d| if (d[0][0] == a and d[0][1] == b) return d[1];
    for (table) |d| if (d[0][0] == b and d[0][1] == a) return d[1];
    return null;
}

test "digraphs: Vim's pairs, either way round" {
    const t = std.testing;
    try t.expectEqual('é', find('e', '\'').?);
    try t.expectEqual('ä', find('a', ':').?);
    try t.expectEqual('→', find('-', '>').?);
    try t.expectEqual('ß', find('s', 's').?);
    try t.expectEqual('€', find('E', 'u').?);
    try t.expectEqual('α', find('a', '*').?);
    try t.expectEqual('é', find('\'', 'e').?); // the other way round
    try t.expectEqual(null, find('q', 'q'));
    // No pair twice.
    for (table, 0..) |d, i| for (table[i + 1 ..]) |e| try t.expect(!std.mem.eql(u8, d[0], e[0]));
}
